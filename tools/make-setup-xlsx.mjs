const BUILTIN = ["VERCEL_URL", "VERCEL_PROJECT_PRODUCTION_URL"];

function walkJs(dir, out = []) {
  const abs = path.join(ROOT, dir);
  if (!fs.existsSync(abs)) return out;
  for (const f of fs.readdirSync(abs, { withFileTypes: true })) {
    if (f.name.startsWith(".")) continue;
    const rel = path.join(dir, f.name);
    if (f.isDirectory()) walkJs(rel, out);
    else if (f.name.endsWith(".js")) out.push(rel);
  }
  return out;
}

const envUsed = [
  ...new Set(
    ["app", "lib", "components"]
      .flatMap((d) => walkJs(d))
      .flatMap((f) => [...read(f).matchAll(/process\.env\.([A-Z0-9_]+)/g)].map((m) => m[1]))
  ),
]
  .filter((v) => !BUILTIN.includes(v))
  .sort((a, b) => {
    const rank = (x) => (ENV_DESC[x] && ENV_DESC[x][0] === "บังคับ" ? 0 : 1);
    return rank(a) - rank(b) || a.localeCompare(b);
  });

