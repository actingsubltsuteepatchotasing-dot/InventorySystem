const BOX_W = 340;
const BOX_H = 52;
const GAP = 38; // ช่องว่างระหว่างกล่อง เป็นที่ให้ลูกศรอยู่พอดี

/** สีของแต่ละสาย — ให้แต่ละผังแยกออกจากกันได้ด้วยสายตา ไม่ต้องอ่านหัวเรื่อง */
const TONE = {
  green: { fill: "EAF5EF", stroke: "2E7D52", color: "1B3D2A" },
  blue: { fill: "E7F0FA", stroke: "0B5FA5", color: "0A3358" },
  amber: { fill: "FBF0E0", stroke: "B26A00", color: "5A3600" },
  grey: { fill: "EFF1F0", stroke: "8A978F", color: "3A423D" },
};

/**
 * วางกล่องเรียงลงมาเป็นแนวตั้ง พร้อมลูกศรคั่นระหว่างกล่อง
 * คืนรายการรูปทรง และตำแหน่ง y ที่ผังนี้จบ เพื่อให้ผังถัดไปวางต่อได้
 */
function column(x, y, title, nodes, tone) {
  const t = TONE[tone] || TONE.green;
  const out = [
    { kind: "label", x, y, w: BOX_W, h: 26, text: title, bold: true, size: 1100, align: "l", color: t.stroke },
  ];

  let cy = y + 32;
  nodes.forEach((text, i) => {
    out.push({ kind: "box", x, y: cy, w: BOX_W, h: BOX_H, text, fill: t.fill, stroke: t.stroke, color: t.color });
    cy += BOX_H;
    if (i < nodes.length - 1) {
      // ลูกศรอยู่กึ่งกลางกล่อง กว้างพอให้เห็นชัดแต่ไม่แย่งพื้นที่ข้อความ
      out.push({ kind: "arrow", x: x + BOX_W / 2 - 9, y: cy + 6, w: 18, h: GAP - 12, fill: t.stroke, stroke: t.stroke });
      cy += GAP;
    }
  });

  return { shapes: out, end: cy };
}

