/* ------------------------------------------- 3. ขั้นตอนการสร้าง (จริง) */

// อ่านบันทึกการแก้ไขจากแผนงาน แล้วแตกเป็นรอบงาน (1) (2) (3) ...
function buildSteps() {
  const start = plan.indexOf("# บันทึกการแก้ไข (Changelog)");
  const body = plan.slice(start);
  const lines = body.split("\n");

  const steps = [];
  let cur = null;

  lines.forEach((line) => {
    // ใส่วันที่เฉพาะรอบที่แผนงานเขียนวันที่ไว้จริง
    // ถ้าสืบทอดวันที่ของรอบก่อนหน้าต่อไปเรื่อย ๆ รอบท้าย ๆ จะได้วันที่ที่ผิดความจริง
    const m = line.match(/^(?:(\d{4}-\d{2}-\d{2})\s+)?\s*\((\d+)\)\s+(.*)$/);
    if (m) {
      if (cur) steps.push(cur);
      cur = { no: Number(m[2]), date: m[1] || "", title: m[3].trim(), detail: [] };
      return;
    }
    if (cur && line.trim()) cur.detail.push(line.trim());
  });
  if (cur) steps.push(cur);

  return steps.map((s) => [
    s.no,
    s.date,
    s.title,
    s.detail
      .join("\n")
      .replace(/\n{3,}/g, "\n\n")
      .slice(0, 2000),
  ]);
}

const steps = buildSteps();

/* ------------------------------------------- 3.1 ประวัติการส่งงานจริง */

// ประวัติ commit เป็นหลักฐานว่างานแต่ละรอบส่งขึ้นจริงเมื่อไร
// แผนงานบันทึกวันที่ไว้แค่สองรอบแรก ส่วนที่เหลือดูจากตรงนี้แทน
function gitLog() {
  try {
    return execFileSync("git", ["log", "--date=short", "--pretty=format:%ad|%h|%s"], {
      cwd: ROOT,
      encoding: "utf8",
      maxBuffer: 8 * 1024 * 1024,
    })
      .trim()
      .split(String.fromCharCode(10))
      .map((l) => l.split("|"))
      .map(([d, h, ...rest]) => [d, h, rest.join("|")]);
  } catch (e) {
    // ไม่ได้อยู่ใน git หรือไม่มี git ในเครื่อง — ไม่ใช่เหตุให้สร้างไฟล์ไม่ได้
    return [["-", "-", "อ่านประวัติ git ไม่ได้: " + e.message]];
  }
}

