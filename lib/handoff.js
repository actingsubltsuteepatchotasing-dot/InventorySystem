// ส่งร่างเอกสารข้ามหน้าจอ — ใช้ตอนกด "สร้างใบขายจากใบนี้"
//
// เก็บไว้ในตัวแปรระดับโมดูล ไม่ได้เก็บใน localStorage หรือ URL เพราะ:
//   1. เป็นของชั่วคราวมาก ๆ อายุแค่ "กดปุ่มแล้วหน้าปลายทาง mount เสร็จ"
//      เก็บลงเครื่องแล้วจะมีร่างค้างข้ามวัน แล้ววันหลังเปิดหน้าขายมาเจอของเก่าโผล่มาเอง
//   2. ทั้งระบบเป็นหน้าเว็บหน้าเดียว (ไม่มีการโหลดหน้าใหม่) ตัวแปรจึงอยู่ครบเสมอ
//   3. ร่างมีชื่อลูกค้าและราคาอยู่ด้วย ไม่ควรไปโผล่ในแถบที่อยู่ของเบราว์เซอร์
//
// อ่านแล้วหายทันที (take ไม่ใช่ get) เพราะร่างหนึ่งใบต้องถูกใช้ครั้งเดียว
// ถ้าอ่านซ้ำได้ การกลับเข้าหน้าขายอีกรอบจะเจอร่างเดิมโผล่มาทับสิ่งที่กำลังกรอกอยู่

let pending = null;

/**
 * ฝากร่างไว้ให้หน้าปลายทาง
 * @param kind รหัสหน้าจอปลายทาง เช่น "invoice"
 * @param data ข้อมูลที่หน้านั้นเข้าใจ
 */
export function putDraft(kind, data) {
  pending = { kind, data };
}

/**
 * รับร่างที่ฝากไว้ แล้วล้างทิ้ง
 * @returns ข้อมูลที่ฝากไว้ หรือ null ถ้าไม่มีของฝากสำหรับหน้านี้
 */
export function takeDraft(kind) {
  if (!pending || pending.kind !== kind) return null;
  const data = pending.data;
  pending = null;
  return data;
}

/** ล้างของฝากทิ้งโดยไม่ใช้ — เผื่อกดยกเลิกกลางทาง */
export function clearDraft() {
  pending = null;
}
