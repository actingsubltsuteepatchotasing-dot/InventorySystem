/** จำนวนจุดตรวจทั้งหมด */
function countChecks() {
  return CRITERIA.reduce((t, c) => t + c.levels.reduce((n, l) => n + l.checks.length, 0), 0);
}

/** จำนวนจุดตรวจที่ระบบตรวจให้เอง */
function countAuto() {
  return CRITERIA.reduce(
    (t, c) => t + c.levels.reduce((n, l) => n + l.checks.filter((ck) => ck.auto).length, 0),
    0
  );
}
