/**
 * จุดอยู่ในรูปหลายเหลี่ยมหรือไม่ (ray casting)
 * นับจำนวนครั้งที่เส้นแนวนอนจากจุดนั้นตัดขอบรูป — คี่คืออยู่ข้างใน
 */
export function inPolygon(x, y, poly) {
  let inside = false;
  for (let i = 0, j = poly.length - 1; i < poly.length; j = i++) {
    const [xi, yi] = poly[i];
    const [xj, yj] = poly[j];
    const hit = yi > y !== yj > y && x < ((xj - xi) * (y - yi)) / (yj - yi) + xi;
    if (hit) inside = !inside;
  }
  return inside;
}

/** ระยะจากจุดถึงส่วนของเส้นตรง */
export function distToSegment(px, py, x1, y1, x2, y2) {
  const dx = x2 - x1;
  const dy = y2 - y1;
  const len2 = dx * dx + dy * dy;
  // เส้นยาวศูนย์ (จุดซ้ำกัน) ให้วัดระยะถึงจุดนั้นตรง ๆ กัน 0/0
  const t = len2 ? Math.max(0, Math.min(1, ((px - x1) * dx + (py - y1) * dy) / len2)) : 0;
  const cx = x1 + t * dx;
  const cy = y1 + t * dy;
  return Math.hypot(px - cx, py - cy);
}

/** จุดอยู่บนเส้นหนาที่ลากผ่านชุดจุดหรือไม่ */
export function onPolyline(x, y, pts, width) {
  const half = width / 2;
  for (let i = 1; i < pts.length; i++) {
    const [x1, y1] = pts[i - 1];
    const [x2, y2] = pts[i];
    if (distToSegment(x, y, x1, y1, x2, y2) <= half) return true;
  }
  return false;
}

/**
 * สีของจุดหนึ่งในตรา — ใช้ลำดับเดียวกับที่ SVG วาดทับกัน
 * ลูกศรอยู่ล่างสุด เปลวไฟทับด้านบน ไส้ในทับอีกที
 * @returns {string|null} สี หรือ null ถ้าโปร่งใส
 */
export function markColorAt(x, y) {
  if (inPolygon(x, y, FLAME_INNER)) return MARK.flameLight;
  if (inPolygon(x, y, FLAME_OUTER)) return MARK.flame;
  if (inPolygon(x, y, ARROW_HEAD)) return MARK.arrow;
  if (onPolyline(x, y, ARROW_PATH, ARROW_WIDTH)) return MARK.arrow;
  return null;
}
