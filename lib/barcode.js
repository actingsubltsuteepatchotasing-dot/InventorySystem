/**
 * เข้ารหัสข้อความเป็นแท่งบาร์โค๊ด Code 128-B
 * @returns {{bars: Array<{x:number,w:number}>, width:number, text:string}|null}
 */
export function encode128(text, moduleWidth) {
  const mw = moduleWidth || 2;
  const s = String(text || "").replace(/[^\x20-\x7E]/g, "");
  if (!s) return null;

  const values = [104]; // START B
  for (let i = 0; i < s.length; i++) values.push(s.charCodeAt(i) - 32);

  let sum = 104;
  for (let i = 1; i < values.length; i++) sum += values[i] * i;
  values.push(sum % 103); // check digit
  values.push(106); // STOP

  const bars = [];
  let x = 0;
  values.forEach((v) => {
    const pattern = C128[v];
    for (let i = 0; i < pattern.length; i++) {
      const w = parseInt(pattern[i], 10) * mw;
      if (i % 2 === 0) bars.push({ x, w }); // ตำแหน่งคู่ = แท่งสีเข้ม
      x += w;
    }
  });

  return { bars, width: x, text: s };
}
