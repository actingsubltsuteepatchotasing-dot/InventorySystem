export const guideOf = (id) => GUIDES[id] || null;

/** สายงานที่มีหน้าจอนี้อยู่ในลำดับ */
export const flowsOf = (id) => FLOWS.filter((f) => f.steps.some((s) => s.screen === id));

/**
 * หน้าจอทั้งหมดที่คู่มืออ้างถึง ใช้ตรวจว่าไม่มีลิงก์ที่ชี้ไปหน้าที่ไม่มีอยู่จริง
 * (ลิงก์เสียในคู่มือแย่กว่าไม่มีลิงก์ เพราะคนกดแล้วไปผิดที่หรือไม่มีอะไรเกิดขึ้น)
 */
export function referencedScreens() {
  const out = new Set();
  FLOWS.forEach((f) => f.steps.forEach((s) => out.add(s.screen)));
  Object.values(GUIDES).forEach((g) => {
    (g.from || []).forEach((x) => out.add(x));
    (g.next || []).forEach((x) => out.add(x));
  });
  return [...out];
}

/** ค้นหาหน้าจอในคู่มือจากคำค้น — ค้นได้ทั้งชื่อ คำอธิบาย ขั้นตอน และข้อควรรู้ */
export function searchGuides(screens, q) {
  const words = String(q || "").trim().toLowerCase().split(/\s+/).filter(Boolean);
  return (screens || []).filter((s) => {
    const g = GUIDES[s.id];
    if (!g) return false;
    if (!words.length) return true;
    const hay = [s.name, s.group, g.what, ...(g.how || []), ...(g.writes || []), g.tip]
      .join(" ")
      .toLowerCase();
    return words.every((w) => hay.includes(w));
  });
}
