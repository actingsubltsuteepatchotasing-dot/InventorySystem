/**
 * สีของแถบความมั่นใจในการจับคู่สินค้า
 *
 * แบ่งหยาบ ๆ สามระดับพอ เพราะคนอ่านต้องตัดสินใจแค่ว่า
 * "ผ่านได้เลย" / "เหลือบดูหน่อย" / "ต้องเลือกเอง"
 * ถ้าไล่เฉดละเอียดกว่านี้จะกลายเป็นตัวเลขที่ไม่มีใครตีความได้
 */
export const scoreKind = (score, productId) => {
  if (!productId) return "err";
  if (score >= 0.95) return "ok";
  return "warn";
};
